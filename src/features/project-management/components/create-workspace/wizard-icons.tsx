/** A React id usable inside `url(#…)`. */
function useSvgId() {
  return `pm-icon-${useId().replace(/[^a-zA-Z0-9_-]/g, '')}`
}

/** A vertical two-stop gradient with an id unique to this icon instance. */
function useGradient(from: string, to: string, box: [number, number, number, number]) {
  const id = useSvgId()
  const [x1, y1, x2, y2] = box
  return {
    fill: `url(#${id})`,
    def: (
      <linearGradient id={id} x1={x1} y1={y1} x2={x2} y2={y2} gradientUnits="userSpaceOnUse">
        <stop stopColor={from} />
        <stop offset="1" stopColor={to} />
      </linearGradient>
    ),
  }
}

